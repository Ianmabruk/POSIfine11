// ===== STOCK =====

export function exportStockPDF(products, ingredientStocks) {
  const headers = ['Name', 'Type', 'Quantity', 'Unit', 'Cost/Unit (KSH)', 'Price (KSH)', 'Status'];
  const rows = [];

  if (products && products.length > 0) {
    products.forEach(p => {
      const qty = p.quantity ?? p.stock ?? 0;
      rows.push([
        p.name || '',
        'Product',
        qty,
        p.unit || 'pcs',
        p.cost_per_unit ?? p.cost ?? '',
        p.price ?? p.selling_price ?? '',
        qty <= 0 ? 'Out of Stock' : 'In Stock'
      ]);
    });
  }

  if (ingredientStocks && ingredientStocks.length > 0) {
    ingredientStocks.forEach(m => {
      const qty = Number(m.quantity || 0);
      const reorder = Number(m.reorder_level || 0);
      rows.push([
        m.name || '',
        'Ingredient',
        qty,
        m.unit || 'units',
        m.cost_per_unit ?? '',
        '',
        reorder > 0 && qty <= reorder ? 'Low Stock' : 'In Stock'
      ]);
    });
  }

  const inStock = rows.filter(r => r[6] === 'In Stock').length;
  const lowStock = rows.filter(r => r[6] === 'Low Stock').length;
  const outOfStock = rows.filter(r => r[6] === 'Out of Stock').length;
  const summary = [
    `Total Items: ${rows.length}`,
    `In Stock: ${inStock}`,
    `Low Stock: ${lowStock}`,
    `Out of Stock: ${outOfStock}`
  ];

  const doc = buildPDF('Stock & Inventory Report', headers, rows, summary);
  doc.save(`stock-inventory-${new Date().toISOString().slice(0, 10)}.pdf`);
}

// ===== CREDIT REQUESTS =====

export function exportCreditRequestsPDF(requests) {
  const headers = ['Date', 'Customer', 'Amount (KSH)', 'Reason', 'Status', 'Cashier', 'Admin Notes'];
  const rows = requests.map(r => [
    formatDate(r.created_at || r.createdAt),
    r.customer_name || r.customerName || '',
    `KSH ${(r.amount || 0).toLocaleString()}`,
    r.reason || '',
    r.status || '',
    r.cashier_name || r.cashierName || '',
    r.admin_notes || r.rejectionReason || ''
  ]);

  const total = requests.reduce((s, r) => s + (r.amount || 0), 0);
  const pending = requests.filter(r => r.status === 'pending').length;
  const approved = requests.filter(r => r.status === 'approved').length;
  const rejected = requests.filter(r => r.status === 'rejected').length;
  const summary = [
    `Total Amount: KSH ${total.toLocaleString()}`,
    `Pending: ${pending}`,
    `Approved: ${approved}`,
    `Rejected: ${rejected}`
  ];

  const doc = buildPDF('Credit Requests Report', headers, rows, summary);
  doc.save(`credit-requests-${new Date().toISOString().slice(0, 10)}.pdf`);
}
